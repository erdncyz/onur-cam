const htmlElement = document.documentElement;
const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
const navToggle = document.querySelector(".nav-toggle");
const navList = document.querySelector(".nav-list");
const heroImages = document.querySelectorAll(".hero-img");
const lightbox = document.getElementById("lightbox");
const lightboxImage = document.getElementById("lightboxImage");
const lightboxCaption = document.getElementById("lightboxCaption");
const lightboxClose = document.querySelector(".lightbox-close");
const contactForm = document.querySelector(".contact-form");

let currentLanguage = localStorage.getItem("lang") || "tr";
let currentTheme = localStorage.getItem("theme") || "light";

function applyTranslations(lang) {
  const dictionary = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      node.placeholder = dictionary[key];
    }
  });

  htmlElement.lang = lang;
  langToggle.textContent = lang.toUpperCase();
}

function applyTheme(theme) {
  htmlElement.setAttribute("data-theme", theme);
  const icon = theme === "dark" ? "fa-sun" : "fa-moon";
  themeToggle.innerHTML = `<i class="fa-regular ${icon}"></i>`;
}

langToggle?.addEventListener("click", () => {
  currentLanguage = currentLanguage === "tr" ? "en" : "tr";
  localStorage.setItem("lang", currentLanguage);
  applyTranslations(currentLanguage);
});

themeToggle?.addEventListener("click", () => {
  currentTheme = currentTheme === "dark" ? "light" : "dark";
  localStorage.setItem("theme", currentTheme);
  applyTheme(currentTheme);
});

navToggle?.addEventListener("click", () => {
  navList?.classList.toggle("open");
});

document.addEventListener("click", (event) => {
  if (!navList || !navToggle) {
    return;
  }

  const clickedInsideMenu = navList.contains(event.target);
  const clickedToggle = navToggle.contains(event.target);
  if (!clickedInsideMenu && !clickedToggle) {
    navList.classList.remove("open");
  }
});

document.querySelectorAll(".nav-list a").forEach((item) => {
  item.addEventListener("click", () => {
    navList?.classList.remove("open");
  });
});

if (heroImages.length > 1) {
  let index = 0;
  setInterval(() => {
    heroImages[index].classList.remove("active");
    index = (index + 1) % heroImages.length;
    heroImages[index].classList.add("active");
  }, 4000);
}

document.querySelectorAll(".gallery-item").forEach((item) => {
  item.addEventListener("click", () => {
    const image = item.querySelector("img");
    if (!image || !lightbox || !lightboxImage) {
      return;
    }

    lightboxImage.src = image.src;
    lightboxImage.alt = image.alt;
    if (lightboxCaption) {
      lightboxCaption.textContent = image.alt || "";
    }
    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  });
});

function closeLightbox() {
  if (!lightbox) {
    return;
  }

  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  if (lightboxCaption) {
    lightboxCaption.textContent = "";
  }
}

lightboxClose?.addEventListener("click", closeLightbox);

lightbox?.addEventListener("click", (event) => {
  if (event.target === lightbox) {
    closeLightbox();
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeLightbox();
  }
});

if (contactForm) {
  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();
    alert(translations[currentLanguage].form_success);
    contactForm.reset();
  });
}

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("show");
      }
    });
  },
  { threshold: 0.16 }
);

document.querySelectorAll(".reveal").forEach((section) => {
  revealObserver.observe(section);
});

document.getElementById("year").textContent = new Date().getFullYear();
applyTranslations(currentLanguage);
applyTheme(currentTheme);